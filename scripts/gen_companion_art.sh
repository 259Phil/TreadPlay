#!/usr/bin/env bash
# Regenerates lib/data/companion_cutouts.dart from the companion cutouts in
# assets/companions/ ({id}.png = Common, {id}-rare.png, {id}-epic.png,
# {id}-legendary.png). Requires ImageMagick (without it: gen_companion_art.py,
# which also lists the _c card images). Run after adding or editing art.
set -euo pipefail
cd "$(dirname "$0")/.."
out=lib/data/companion_cutouts.dart
{
  echo '// GENERATED by scripts/gen_companion_art.sh. Do not edit by hand.'
  echo
  echo "import 'dart:ui';"
  echo
  echo '/// Every bundled companion cutout: image size and the box around the'
  echo '/// creature (non-transparent pixels), both in image pixels.'
  echo 'const Map<String, ({Size size, Rect body})> companionCutouts = {'
  for f in assets/companions/*.png; do
    id=$(basename "$f" .png)
    [[ $id =~ ^[a-z]+(-rare|-epic|-legendary)?$ ]] || continue
    read -r W H B <<<"$(identify -format '%w %h %@' "$f")"
    [[ $B =~ ^([0-9]+)x([0-9]+)\+([0-9]+)\+([0-9]+)$ ]]
    bw=${BASH_REMATCH[1]} bh=${BASH_REMATCH[2]} bx=${BASH_REMATCH[3]} by=${BASH_REMATCH[4]}
    echo "  '$id': (size: Size($W, $H), body: Rect.fromLTWH($bx, $by, $bw, $bh)),"
  done
  echo '};'
} > "$out"
dart format "$out" >/dev/null
